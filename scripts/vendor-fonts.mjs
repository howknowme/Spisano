// Copies the Manrope and Unbounded webfonts (Latin + Cyrillic) from @fontsource into fonts/,
// so the app never calls Google Fonts. Run after updating the font packages: npm run fonts
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';

const root = new URL('..', import.meta.url);
const want = { manrope: [400, 500, 600, 700], unbounded: [500, 700] };
const subsets = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'];
await mkdir(new URL('fonts/', root), { recursive: true });

let css = '/* Generated by scripts/vendor-fonts.mjs from @fontsource (SIL Open Font License 1.1) */\n';
for (const [family, weights] of Object.entries(want)) {
  for (const w of weights) {
    const src = await readFile(new URL(`node_modules/@fontsource/${family}/${w}.css`, root), 'utf8');
    for (const block of src.split('/* ').slice(1)) {
      const name = block.slice(0, block.indexOf(' */'));
      if (!subsets.some((s) => name === `${family}-${s}-${w}-normal`)) continue;
      const file = `${name}.woff2`;
      await copyFile(new URL(`node_modules/@fontsource/${family}/files/${file}`, root), new URL(`fonts/${file}`, root));
      css += '/* ' + block
        .replace(/src: url\([^)]*\.woff2\) format\('woff2'\), url\([^)]*\) format\('woff'\);/, `src: url(./${file}) format('woff2');`);
    }
  }
}
await writeFile(new URL('fonts/fonts.css', root), css);
console.log('fonts/fonts.css written');
